"""Create publication-ready schematic figures for the CPSS DCC paper.

The figures are data-independent. Result plots remain generated by
plot_dcc_paper_figures.py from a frozen method_metrics.csv.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch, Polygon, Rectangle


COLORS = {
    "ink": "#263238",
    "muted": "#66727A",
    "line": "#7B858B",
    "grid": "#D9DEE1",
    "decision": "#2F80C0",
    "probe": "#55AEE0",
    "compress": "#007A9E",
    "raw": "#D66A16",
    "transfer": "#E59C00",
    "restore": "#B9689E",
    "decision_fill": "#EAF4FA",
    "compress_fill": "#E9F5F7",
    "raw_fill": "#FFF0E6",
    "transfer_fill": "#FFF7E2",
    "restore_fill": "#FAF0F7",
}


def style() -> None:
    plt.rcParams.update(
        {
            "font.family": "serif",
            "font.serif": ["STIX Two Text", "STIXGeneral", "DejaVu Serif"],
            "mathtext.fontset": "stix",
            "font.size": 8,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "savefig.facecolor": "white",
            "figure.facecolor": "white",
        }
    )


def save(fig: plt.Figure, output: Path, stem: str) -> None:
    output.mkdir(parents=True, exist_ok=True)
    fig.savefig(output / f"{stem}.pdf", bbox_inches="tight", metadata={"Title": stem})
    fig.savefig(output / f"{stem}.eps", bbox_inches="tight")
    fig.savefig(output / f"{stem}.png", dpi=450, bbox_inches="tight")
    plt.close(fig)


def arrow(
    ax: plt.Axes,
    start: tuple[float, float],
    end: tuple[float, float],
    *,
    color: str = COLORS["line"],
    lw: float = 0.9,
    style: str = "-|>",
    rad: float = 0.0,
    mutation: float = 8.0,
    ls: str = "-",
) -> None:
    ax.add_patch(
        FancyArrowPatch(
            start,
            end,
            arrowstyle=style,
            mutation_scale=mutation,
            linewidth=lw,
            linestyle=ls,
            color=color,
            connectionstyle=f"arc3,rad={rad}",
            shrinkA=2,
            shrinkB=2,
            zorder=6,
        )
    )


def box(
    ax: plt.Axes,
    x: float,
    y: float,
    w: float,
    h: float,
    title: str,
    subtitle: str,
    *,
    edge: str = COLORS["line"],
    face: str = "white",
    title_size: float = 8.0,
    subtitle_size: float = 6.5,
    rounding: float = 0.008,
) -> None:
    ax.add_patch(
        FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle=f"round,pad=0.004,rounding_size={rounding}",
            linewidth=0.9,
            edgecolor=edge,
            facecolor=face,
            zorder=3,
        )
    )
    ax.text(
        x + w / 2,
        y + h * 0.62,
        title,
        ha="center",
        va="center",
        fontsize=title_size,
        color=COLORS["ink"],
        zorder=4,
    )
    ax.text(
        x + w / 2,
        y + h * 0.27,
        subtitle,
        ha="center",
        va="center",
        fontsize=subtitle_size,
        color=COLORS["muted"],
        linespacing=1.15,
        zorder=4,
    )


